create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'visitor' check (role in ('visitor', 'business_pending', 'business_verified', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  icon text,
  created_at timestamptz not null default now()
);

create table if not exists public.businesses (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid references auth.users(id) on delete set null,
  category_id bigint references public.categories(id) on delete set null,
  name text not null,
  description text,
  category text,
  address text,
  province text,
  canton text,
  district text,
  latitude numeric,
  longitude numeric,
  phone text,
  whatsapp text,
  email text,
  website text,
  image_url text,
  budget_level text check (budget_level is null or budget_level in ('bajo', 'medio', 'premium')),
  is_active boolean not null default true,
  is_verified boolean not null default false,
  verification_status text not null default 'pending' check (verification_status in ('pending', 'verified', 'rejected')),
  created_at timestamptz not null default now()
);

create table if not exists public.favorites (
  user_id uuid not null references auth.users(id) on delete cascade,
  business_id uuid not null references public.businesses(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, business_id)
);

create table if not exists public.reviews (
  id uuid primary key default gen_random_uuid(),
  business_id uuid not null references public.businesses(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  body text not null check (char_length(body) between 3 and 1000),
  moderation_status text not null default 'published' check (moderation_status in ('published', 'hidden', 'pending')),
  created_at timestamptz not null default now(),
  unique (business_id, user_id)
);

