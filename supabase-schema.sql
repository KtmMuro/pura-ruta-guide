create policy "Perfiles públicos para usuarios autenticados" on public.profiles
  for select to authenticated using (true);
create policy "Usuario crea su perfil" on public.profiles
  for insert to authenticated with check (auth.uid() = id);
create policy "Usuario actualiza su perfil" on public.profiles
  for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);
create policy "Categorías visibles" on public.categories
  for select to anon, authenticated using (true);
create policy "Negocios verificados visibles" on public.businesses
  for select to anon, authenticated using (
    owner_id = auth.uid()
    or (
      coalesce(is_active, true) = true
      and (
        coalesce(is_verified, false) = true
        or verification_status = 'verified'
      )
    )
  );
create policy "Propietario crea su negocio" on public.businesses
  for insert to authenticated with check (owner_id = auth.uid());
create policy "Propietario actualiza su negocio" on public.businesses
  for update to authenticated using (owner_id = auth.uid()) with check (owner_id = auth.uid());
create policy "Usuario consulta favoritos propios" on public.favorites
  for select to authenticated using (auth.uid() = user_id);
create policy "Usuario agrega favoritos propios" on public.favorites
  for insert to authenticated with check (auth.uid() = user_id);
create policy "Usuario elimina favoritos propios" on public.favorites
  for delete to authenticated using (auth.uid() = user_id);
create policy "Reseñas publicadas visibles" on public.reviews
  for select to anon, authenticated using (moderation_status = 'published' or auth.uid() = user_id);
create policy "Usuario crea su reseña" on public.reviews
  for insert to authenticated with check (auth.uid() = user_id);
