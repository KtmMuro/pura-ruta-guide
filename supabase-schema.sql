create policy "Fotos de negocio visibles"
on storage.objects for select
to public
using (bucket_id = 'business-photos');

create policy "Usuarios autenticados suben fotos de negocio"
on storage.objects for insert
to authenticated
with check (
  bucket_id = 'business-photos'
  and auth.uid()::text = (storage.foldername(name))[1]
);

create policy "Dueño actualiza su foto de negocio"
on storage.objects for update
to authenticated
using (
  bucket_id = 'business-photos'
  and auth.uid()::text = (storage.foldername(name))[1]
)
with check (
  bucket_id = 'business-photos'
  and auth.uid()::text = (storage.foldername(name))[1]
);

create policy "Dueño elimina su foto de negocio"
on storage.objects for delete
to authenticated
using (
  bucket_id = 'business-photos'
  and auth.uid()::text = (storage.foldername(name))[1]
);
